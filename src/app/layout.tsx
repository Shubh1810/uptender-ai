import type { Metadata, Viewport } from "next";
import { Analytics } from "@vercel/analytics/next";
import { Suspense } from "react";
import { CookieBanner } from "@/components/layout/cookie-banner";
import { PostHogProvider, PostHogPageView } from "@/lib/analytics/provider";
import { SITE_NAME, SITE_URL } from "@/lib/site";
import { fontVariables } from "@/lib/fonts";
import { DEFAULT_DESCRIPTION, DEFAULT_TITLE, KEYWORDS, TITLE_TEMPLATE, structuredData } from "@/features/marketing/seo";
import "./globals.css";

/**
 * Site-wide defaults. Pages override `title`, `description` and
 * `alternates.canonical` with their own `export const metadata`.
 *
 * Generated by file conventions in this folder (don't add <link> tags by hand):
 *   icon.png, apple-icon.png          → favicons / iOS home screen icon
 *   manifest.ts                       → /manifest.webmanifest (installable app)
 *   opengraph-image.tsx, twitter-image.tsx → 1200×630 share card
 *   sitemap.ts, robots.ts             → /sitemap.xml, /robots.txt
 *
 * No canonical here on purpose: a canonical set in the root layout is
 * inherited by every page and tells Google they're all copies of the homepage.
 */
export const metadata: Metadata = {
  metadataBase: new URL(SITE_URL),
  title: { default: DEFAULT_TITLE, template: TITLE_TEMPLATE },
  description: DEFAULT_DESCRIPTION,
  keywords: KEYWORDS,
  applicationName: SITE_NAME,
  authors: [{ name: SITE_NAME, url: SITE_URL }],
  creator: SITE_NAME,
  publisher: SITE_NAME,
  category: "business",
  robots: {
    index: true,
    follow: true,
    googleBot: {
      index: true,
      follow: true,
      "max-video-preview": -1,
      "max-image-preview": "large",
      "max-snippet": -1,
    },
  },
  openGraph: {
    type: "website",
    locale: "en_IN",
    siteName: SITE_NAME,
    title: DEFAULT_TITLE,
    description: DEFAULT_DESCRIPTION,
  },
  twitter: {
    card: "summary_large_image",
    title: DEFAULT_TITLE,
    description: DEFAULT_DESCRIPTION,
  },
  appleWebApp: {
    capable: true,
    title: SITE_NAME,
    statusBarStyle: "default",
  },
  formatDetection: { telephone: false },
  // Set these in Vercel once you add the site in Search Console / Bing Webmaster
  // Tools. When unset, the tags are simply omitted.
  verification: {
    google: process.env.NEXT_PUBLIC_GOOGLE_SITE_VERIFICATION,
    other: process.env.NEXT_PUBLIC_BING_SITE_VERIFICATION
      ? { "msvalidate.01": process.env.NEXT_PUBLIC_BING_SITE_VERIFICATION }
      : undefined,
  },
};

export const viewport: Viewport = {
  width: "device-width",
  initialScale: 1,
  themeColor: "#ffffff",
};

/** JSON-LD, with `<` escaped so the payload can't close the script tag. */
const jsonLd = JSON.stringify(structuredData()).replace(/</g, "\\u003c");

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en-IN">
      <head>
        <script type="application/ld+json" dangerouslySetInnerHTML={{ __html: jsonLd }} />
      </head>
      <body className={`${fontVariables} antialiased overflow-x-clip`}>
        <PostHogProvider>
          <Suspense fallback={null}>
            <PostHogPageView />
          </Suspense>
          {children}
          <CookieBanner />
        </PostHogProvider>
        <Analytics />
      </body>
    </html>
  );
}
